<?php
/**
 * Server renderer for the Note cover block.
 *
 * The queried post supplies the metadata and the cover: the featured image when
 * the post has one, the accessible typographic artwork otherwise. A post-less
 * render shows the same artwork with the deterministic metadata fallbacks, and
 * the block never queries a post of its own.
 *
 * Text content stays on the same line as its tag — extra whitespace inside a
 * text-bearing element changes how the theme's `text-wrap` rules balance lines.
 *
 * @var array<string, mixed> $attributes Block attributes.
 *
 * @package Doclap
 */

declare( strict_types=1 );

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

$doclap_post         = doclap_queried_post();
$doclap_id           = $doclap_post ? (int) $doclap_post->ID : 0;
$doclap_raw          = $doclap_post ? (string) $doclap_post->post_content : '';
$doclap_categories   = $doclap_id ? get_the_category( $doclap_id ) : array();
$doclap_category     = ! empty( $doclap_categories )
	? $doclap_categories[0]->name
	: __( 'Uncategorized', 'doclap' );
$doclap_reading_time = doclap_reading_time( $doclap_raw );
$doclap_reading      = sprintf(
	_n( '%d min read', '%d min read', $doclap_reading_time, 'doclap' ),
	$doclap_reading_time,
);
// Section colours are optional: an empty attribute emits nothing, so an unset
// colour keeps the theme's default for that property.
$doclap_colour_style = '';

foreach (
	array(
		'sectionBg'      => '--doclap-block-bg',
		'sectionHeading' => '--doclap-block-heading',
		'sectionText'    => '--doclap-block-text',
	) as $doclap_colour_attr => $doclap_colour_var
) {
	$doclap_colour_value = trim( (string) ( $attributes[ $doclap_colour_attr ] ?? '' ) );

	if ( '' !== $doclap_colour_value ) {
		$doclap_colour_style .= $doclap_colour_var . ':' . $doclap_colour_value . ';';
	}
}

$doclap_wrapper = get_block_wrapper_attributes(
	array( 'class' => doclap_scope_class( 'doclap-note-cover', array( 'section' ) ), 'style' => $doclap_colour_style ),
);
?>
<section <?php
	echo $doclap_wrapper; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- escaped by core.
?>>
	<div class="container">
		<div class="article-meta">
			<span><?php echo esc_html( (string) ( $attributes['articleMetaPrefix'] ?? __( 'ĐỘC LẬP / EDITORIAL NOTES', 'doclap' ) ) ); ?></span>
			<span><?php echo esc_html( $doclap_category ); ?></span>
			<span><?php echo esc_html( $doclap_reading ); ?></span>
		</div>
		<div class="article-cover">
			<?php if ( $doclap_id && has_post_thumbnail( $doclap_id ) ) : ?>
				<?php
				echo get_the_post_thumbnail(
					$doclap_id,
					'full',
					array( 'class' => 'article-cover__image' ),
				); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- generated by core.
				?>
			<?php else : ?>
				<div
					class="artwork motion-art"
					role="img"
					aria-label="<?php esc_attr_e( 'Typography graphic: Slow.', 'doclap' ); ?>"
				>
					<span class="art-label"><?php esc_html_e( 'STUDY / MOTION', 'doclap' ); ?></span>
					<span class="art-word"><?php esc_html_e( 'Slow.', 'doclap' ); ?></span>
				</div>
			<?php endif; ?>
		</div>
	</div>
</section>
